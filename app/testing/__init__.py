def starts_lesson(data: str) -> bool:
    """
    Эта кнопка начинает занятие?

    СПРАШИВАТЬ НАДО ПРО ДЕЙСТВИЕ, А НЕ ПРО СТРОКУ. Кнопка «начать
    занятие» живёт на четырёх экранах — домашнем, в напоминании, в итоге
    круга и во вступлении, — и с 13 октября каждая несёт пометку своей
    двери («learn_now:reminder»), чтобы петлю возврата было чем измерить.
    Проверки, сверявшие точное равенство с «learn_now», упали все
    одиннадцать — и упали НА РОВНОМ МЕСТЕ: кнопка работает, обработчик
    тот же, изменилась только пометка.

    Поэтому признак назван один раз здесь. Добавится пятая дверь — ни одна
    проверка не заметит, и это правильно: они проверяют, что из этого
    экрана можно начать заниматься, а не как называется кнопка.
    """
    return data.split(":")[0] == "learn_now"


def lesson_button(buttons: list[str]) -> str | None:
    """Первая кнопка из списка, которая начинает занятие."""
    for data in buttons:
        if starts_lesson(data):
            return data
    return None


