"""
Ищет РУССКОЕ СЛОВО, попавшее в украинскую ячейку.

Зачем. Блок 62 дал это пять раз на 200 рядов: `на полу` вместо «на
підлозі», `дома` вместо «вдома», `босс` вместо «бос», `Знаружи`
вместо «Надворі», `овсянка` вместо «вівсянка». Такое слово ученик
заучивает как украинское, а оно русское — и это хуже опечатки:
опечатку видно, а здесь всё выглядит правильным.

Как ищется. База сама себе словарь, и на этот раз — ПОПЕРЁК СТОЛБЦОВ.
В базе 12 902 ряда, у каждого есть и русские, и украинские ячейки.
Значит есть два корпуса одного размера: 28 590 русских словоформ и
27 759 украинских. Слово, которое в русском корпусе встречается часто,
а в украинском один раз, — это с большой вероятностью то самое
единственное попадание не в свою ячейку.

Порог поставлен так: не меньше шести вхождений в русском и не больше
одного в украинском. Первый проход был сделан иначе — «ни разу в
украинском» — и дал ровно ноль. Причина поучительная: дефект сам
заносит слово в чужой корпус, и условие «ни разу» его же и вычёркивает.
Примета съела свою находку.

Чего примета не умеет, и это надо знать точно.

  1. Обратное направление НЕ РАБОТАЕТ. Украинское слово в русской
     ячейке примета искала тем же способом и дала 13 попаданий, из
     которых настоящих ноль: `по старому городу`, `к вокзалу`, `на
     боку`, `предан суду` — всё это правильный русский. Причина в том,
     что формы на -у/-ому в русском обычны, но в русских ячейках базы
     встречаются реже, чем в украинских. То есть сработал перекос
     корпуса, а не язык. Это направление в примету не включено.

  2. Русский инфинитив на -ть совпадает с украинским 3-м лицом:
     `кричать`, `вводить`, `чистить`, `переходить`, `справиться` — всё
     это законные украинские формы, и примета давала их пачкой. Отсюда
     фильтр: слова на -ть и -ться не показываются вовсе. Он отсекает
     их все и не теряет ни одного настоящего.

  3. Одно слово приметой не находится вообще. В ряду 16859 стоит
     русская фраза `чтобы остановить сварку` — а «сварка» по-русски
     это сварка металла, и имелась в виду украинская «сварка», ссора.
     Украинское слово в русской ячейке, то самое направление, которое
     не работает. Найдено глазами, и иначе найдено быть не могло.

Итог: 27 попаданий сырьём, 7 из них законные украинские слова того же
написания (`город` это огород, `глава` — глава книги, `письмо` —
письмо как система знаков) и вынесены в белый список. Осталось 20, и
все 20 настоящие. Гейтом примета всё равно быть не может: белый список
придётся дополнять при каждом пополнении базы.

    python -m app.scripts.scan_ru_in_uk
"""

from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

from sqlalchemy import create_engine, text

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from app.config import settings  # noqa: E402

WORD = re.compile(r"[а-яёіїєґА-ЯЁІЇЄҐ'’-]{4,}")

MIN_HOME = 6     # сколько раз слово должно встречаться в русских ячейках
MAX_OTHER = 1    # и сколько раз максимум — в украинских

# Законные украинские слова, совпадающие с русскими по форме. Собран
# чтением всех попаданий: `город` это огород, `глава` — глава книги,
# `письмо` — письмо как система знаков, `торжество` — торжество,
# `прав` — родительный от «право», `другим` — от «другий».
LEGIT = {
    "заново", "задачу", "задача", "задачі", "хороша", "продажу",
    "город", "глава", "письмо", "торжество", "прав", "другим",
}


def suspects(ru: Counter, uk: Counter) -> set[str]:
    return {
        w for w, c in ru.items()
        if c >= MIN_HOME and uk[w] <= MAX_OTHER
        # русский инфинитив совпадает с украинским 3-м лицом
        and not w.endswith(("ть", "ться"))
        and w not in LEGIT
    }


def selfcheck() -> None:
    """Проверяет саму логику отбора на придуманных корпусах."""
    ru = Counter({"стакан": 9, "кричать": 9, "заново": 9, "склянка": 1,
                  "книга": 9})
    uk = Counter({"стакан": 1, "кричать": 7, "заново": 4, "склянка": 9,
                  "книга": 9})
    got = suspects(ru, uk)
    want = {"стакан"}
    if got != want:
        print(f"САМОПРОВЕРКА УПАЛА: отобрано {sorted(got)}, "
              f"а надо {sorted(want)}")
        sys.exit(1)
    print("самопроверка: отбор на придуманных корпусах верен "
          "(«стакан» взят, «кричать» отсечён по -ть, «заново» по "
          "белому списку, «книга» и «склянка» по частоте)\n")


def main() -> None:
    selfcheck()
    engine = create_engine(settings.DATABASE_URL_SYNC)
    with engine.connect() as conn:
        rows = conn.execute(text(
            "SELECT id, word_de, translation_ru, example_ru, "
            "translation_uk, example_uk FROM words ORDER BY id")).all()

    ru, uk = Counter(), Counter()
    for _, _, tr_ru, ex_ru, tr_uk, ex_uk in rows:
        for v in (tr_ru, ex_ru):
            ru.update(t.lower() for t in WORD.findall(v or ""))
        for v in (tr_uk, ex_uk):
            uk.update(t.lower() for t in WORD.findall(v or ""))

    print(f"русских словоформ: {len(ru)}, украинских: {len(uk)}")
    bad = suspects(ru, uk)
    print(f"русских форм под подозрением: {len(bad)}")

    found = []
    for wid, word, _, _, tr_uk, ex_uk in rows:
        for col, val in (("translation_uk", tr_uk), ("example_uk", ex_uk)):
            for t in WORD.findall(val or ""):
                if t.lower() in bad:
                    found.append((wid, word, col, t, val))

    print(f"ячеек с русским словом: {len(found)}\n")
    for wid, word, col, t, val in found:
        print(f"  {wid:>6}  {word:<22} {col:<14} [{t}]")
        print(f"          {val}")


if __name__ == "__main__":
    main()
