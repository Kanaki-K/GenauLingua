"""
Ищет украинские АКТИВНЫЕ ДІЄПРИКМЕТНИКИ на -ючий/-учий — кальку
русских форм на -ющий/-ущий.

Зачем. В блоке 60 подряд попались две такие формы:

    Ці голодуючі тварини терміново потребували допомоги
    Лінчуючі взяли закон у свої руки

В украинском активных дієприкметників теперішнього часу практически
нет: там, где русский говорит «голодающий», украинский говорит
«виголоднілий» или разворачивает в «той, що голодує». Машина же берёт
русскую форму и меняет «-ющий» на «-ючий». Получается слово, которого
нет, но которое выглядит безупречно украинским — и ученик его
запоминает.

Как ищется. Форма видна по строению: основа + `юч|уч|ач|яч` +
прилагательное окончание. Регулярка их и собирает.

Беда в том, что по тому же шаблону строится множество ЗАКОННЫХ слов
трёх разных родов:

  1. давно устоявшиеся прилагательные: `блискучий`, `балакучий`,
     `гнітючий`, `неминучий`, `сліпучий`, `квітучий`, `смердючий`,
     `нерішучий`, `неродючий`, `терплячий`, `тремтячий`;
  2. слова, где `яч`/`ач` вообще не суффикс дієприкметника:
     `дитячий`, `гарячий`, `звірячий`, `незрячий`, `добрячий`;
  3. существительные на `-ач`: `передача`, `викрадач`, `користувач`,
     `підпалювач`, `автовідповідач`, `телеведучий`, `головуючий`.

Отличить их от кальки формальным правилом нельзя: строение одно и то
же. Поэтому точность приметы целиком держится на белом списке ниже, и
он собран не догадкой, а чтением: примета прогнана по базе, все 110
разных форм просмотрены глазами по одной, и каждая отнесена либо в
белый список, либо в правку. Это честная цена: примета сужает 206
попаданий до тех, что надо прочитать, а решение остаётся за человеком.

Третий род — слова, которые строго говоря калька, но которые украинские
словари уже зарегистрировали: `вражаючий` (31 ячейка) и `хвилюючий`
(4 ячейки). Их примета показывает отдельным списком и не правит: это
не ошибка, а вопрос вкуса, и переписывать 35 ячеек по вкусу — не дело
проверки. Отдельный список нужен, чтобы они не терялись в белом: белый
список означает «законно», а этот — «решено не трогать».

Чего примета не умеет. Новая калька, которой в базе ещё нет, в белый
список не попадёт — и это правильно, её покажут. Но и наоборот: если
в базу придёт законное слово такого строения, примета его покажет
ложно, и белый список придётся дополнить. Гейтом поэтому быть не может.

    python -m app.scripts.scan_uk_active_participle
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from sqlalchemy import create_engine, text

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from app.config import settings  # noqa: E402

FORM = re.compile(
    r"\b[а-яіїєґА-ЯІЇЄҐ'’-]*(?:юч|уч|ач|яч)"
    r"(?:ий|ого|ому|им|ім|их|ими|ої|ій|ою|а|у|е|і)\b"
)

MIN_LEN = 8

# Законные слова того же строения. Собран чтением всех попаданий.
LEGIT_STEMS = {
    # устоявшиеся прилагательные
    "блискуч", "балакуч", "небалакуч", "гнітюч", "неминуч", "сліпуч",
    "квітуч", "смердюч", "нерішуч", "неродюч", "терпляч", "нетерпляч",
    "тремтяч", "дрижач", "палаюч", "правляч", "люблячи", "любляч",
    "віруюч", "працююч", "непрацююч", "волаюч", "нержавіюч",
    # `яч`/`ач` не суффикс дієприкметника
    "дитяч", "гаряч", "звіряч", "незряч", "добряч",
    # существительные на -ач и -учий
    "передач", "телепередач", "самовіддач", "викрадач", "користувач",
    "автовідповідач", "переслідувач", "підглядач", "підпалювач",
    "телеведуч", "головуюч", "комплектуюч", "відплач",
}


# Калька, но словарями зарегистрированная. Показываем, не правим.
REGISTERED_STEMS = {"вражаюч", "хвилююч"}


def legit(word: str) -> bool:
    w = word.lower()
    return any(w.startswith(s) for s in LEGIT_STEMS)


def registered(word: str) -> bool:
    w = word.lower()
    return any(w.startswith(s) for s in REGISTERED_STEMS)


def hits(value: str | None) -> list[str]:
    if not value:
        return []
    return [m.group(0) for m in FORM.finditer(value)
            if len(m.group(0)) >= MIN_LEN and not legit(m.group(0))
            and not registered(m.group(0))]


def soft_hits(value: str | None) -> list[str]:
    if not value:
        return []
    return [m.group(0) for m in FORM.finditer(value)
            if len(m.group(0)) >= MIN_LEN and registered(m.group(0))]


GOOD = [
    "Його усмішка була блискуча",
    "Це був неминучий кінець",
    "Дитячому майданчику потрібен ремонт",
    "Передача починається о восьмій",
    "Поліція затримала викрадача",
    "Він дуже балакучий і не вміє слухати",
    "Терплячий учитель усе пояснив ще раз",
]
BAD = [
    "Ці голодуючі тварини терміново потребували допомоги",
    "Лінчуючі взяли закон у свої руки",
    "Це був шокуючий результат",
    "Існуючий порядок треба змінити",
    "Він купив енергозберігаючі лампи",
]


def selfcheck() -> None:
    for s in GOOD:
        if hits(s):
            print(f"САМОПРОВЕРКА УПАЛА: ложное срабатывание на {s!r} "
                  f"— {hits(s)}")
            sys.exit(1)
    for s in BAD:
        if not hits(s):
            print(f"САМОПРОВЕРКА УПАЛА: пропущено {s!r}")
            sys.exit(1)
    print(f"самопроверка: {len(GOOD)} правильных и {len(BAD)} "
          f"испорченных строк разобраны верно\n")


def main() -> None:
    selfcheck()
    engine = create_engine(settings.DATABASE_URL_SYNC)
    with engine.connect() as conn:
        rows = conn.execute(text(
            "SELECT id, word_de, translation_uk, example_uk FROM words "
            "ORDER BY id")).all()

    print(f"прочитано рядов: {len(rows)}")
    total, soft = 0, 0
    for wid, word, tr, ex in rows:
        for col, val in (("translation_uk", tr), ("example_uk", ex)):
            got = hits(val)
            if got:
                total += 1
                print(f"  {wid:>6}  {word:<22} {col:<14} "
                      f"[{', '.join(got)}]")
                print(f"          {val}")
    for wid, word, tr, ex in rows:
        for col, val in (("translation_uk", tr), ("example_uk", ex)):
            if soft_hits(val):
                soft += 1
    print(f"\nячеек с калькой: {total}")
    print(f"ячеек с зарегистрированной калькой (решено не трогать): {soft}")


if __name__ == "__main__":
    main()
