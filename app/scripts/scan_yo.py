def selfcheck() -> None:
    print("=== самопроверка шаблона ===")
    false_hits = [(s, PATTERN.search(s).group(0)) for s in GOOD
                  if PATTERN.search(s)]
    misses = [s for s in BAD if not PATTERN.search(s)]
    if false_hits:
        print("  ПРОВАЛ: верные строки объявлены битыми:")
        for s, w in false_hits:
            print(f"    {s!r} — зацепилось за {w!r}")
    if misses:
        print("  ПРОВАЛ: битые строки не найдены:")
        for s in misses:
            print(f"    {s!r}")
    if false_hits or misses:
        sys.exit("шаблон негоден, работать нельзя")
    print(f"  шаблон отличает верное от битого ({len(FORMS)} форм)")


async def main() -> int:
    selfcheck()
    engine = create_async_engine(settings.DATABASE_URL, echo=False)
    async with engine.connect() as conn:
        total = await conn.scalar(text("SELECT count(*) FROM words"))
        print(f"\n=== проверено слов: {total} ===\n")
        hits = 0
        for col in ("example_ru", "translation_ru"):
            rows = (await conn.execute(text(
                f"SELECT id, word_de, {col} FROM words "
                f"WHERE {col} IS NOT NULL ORDER BY id"
            ))).all()
            found = [(i, w, v, PATTERN.findall(v)) for i, w, v in rows
                     if PATTERN.search(v)]
            if not found:
                continue
            hits += len(found)
            print(f"{col}: {len(found)}")
            for i, w, v, words in found:
                print(f"  {i:>7} {w:<18} {', '.join(words):<22} {v!r}")
            print()
        print("потерянной «ё» нет" if not hits else f"всего ячеек: {hits}")
    await engine.dispose()
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
