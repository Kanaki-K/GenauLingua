"""
Ищет чужой язык внутри перевода.

Зачем. В блоке 46 в украинском примере ряда `handhaben` стояло
`Потрібно обережно обращаться з цими інструментами` — целое русское
слово посреди украинской фразы. Это не русизм (русизм хотя бы выглядит
по-украински), а прямо чужое слово, и ни одна прежняя примета его не
видела: буквы все кириллические, падеж на месте, строка читается.

Тем же блоком в турецком примере ряда `Transfer` нашлось
`çok para kostar` — немецкий глагол в турецкой фразе.

Три приметы, каждая решаемая механически:

1. Русские буквы `ы`, `ъ`, `э`, `ё` в украинской ячейке. В украинском
   алфавите их нет вовсе.
2. Украинские буквы `і`, `ї`, `є`, `ґ` в русской ячейке. В русском
   алфавите их нет вовсе.
3. Короткий список русских слов, у которых украинского двойника с тем
   же написанием не бывает: `обращаться`, `очень`, `тоже`, `сейчас`,
   `который`, `нужно`, `сказал`, `сделать`, `спасибо`, `поэтому`.
   Список намеренно короткий: слово попадает в него только если его
   украинское написание гарантированно другое. После блока 47 в него
   добавлены словоформы `залог`, `курица`, `коготь`, `застройник` —
   все три ряда нашёл глаз, буквенная примета их видеть не могла.
   Склонять машинно нельзя: можно наткнуться на украинское слово,
   поэтому формы перечислены поимённо.

Что примета принципиально не ловит: немецкое или английское слово
внутри турецкой или польской ячейки. Латиница у всех четырёх языков
общая, и `kostar` от турецкого слова машинно не отличить — нужен
словарь турецкого, которого здесь нет. Такие случаи только глазами.

Самопроверка: на заведомо правильных строках срабатывать не должно, на
заведомо испорченных — должно. Если хоть одна не сошлась, скрипт падает
и ничего не печатает.

    python -m app.scripts.scan_lang_leak
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from sqlalchemy import create_engine, text

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from app.config import settings  # noqa: E402

RU_ONLY_LETTERS = re.compile(r"[ыъэёЫЪЭЁ]")
UK_ONLY_LETTERS = re.compile(r"[іїєґІЇЄҐ]")
RU_ONLY_WORDS = re.compile(
    # Служебные и частотные слова, у которых украинское написание
    # гарантированно другое.
    r"\b(обращаться|очень|тоже|сейчас|который|нужно|сказал|сделать"
    r"|спасибо|поэтому|здесь|всегда|сегодня|почему|чтобы|если|когда"
    r"|хорошо|деньги|вещь|девушка|мальчик"
    # Добавлено после блока 47: эти три ряда буквенная примета не видела,
    # потому что буквы все украинские. Формы перечислены поимённо —
    # склонять машинно нельзя, можно наткнуться на украинское слово.
    r"|залог|залога|залогом"
    r"|курица|курицу|курицы|курицей"
    r"|коготь|когтем|когти|когтя"
    r"|застройник|застройника|застройники)\b",
    re.IGNORECASE,
)


def uk_hit(s: str) -> str | None:
    m = RU_ONLY_LETTERS.search(s)
    if m:
        return f"русская буква «{m.group()}»"
    m = RU_ONLY_WORDS.search(s)
    if m:
        return f"русское слово «{m.group()}»"
    return None


def ru_hit(s: str) -> str | None:
    m = UK_ONLY_LETTERS.search(s)
    if m:
        return f"украинская буква «{m.group()}»"
    return None


GOOD_UK = [
    "Потрібно обережно поводитися з цими інструментами",
    "Він дуже втомився після роботи",
    "Я теж іду з вами",
    "Зараз немає часу",
    "Той, який стоїть праворуч",
    "Мені потрібно піти",
    "Дякую за допомогу",
    "Тому я залишився вдома",
    # украинские слова, похожие на запрещённые русские формы
    "Ти отримаєш вісім центів застави назад",
    "Орел хапає курку своїм кігтем",
    "Будівельний підрядник завершив проект вчасно",
    "Годі вже про це говорити",
    "Вона тут завжди сьогодні ввечері",
]
BAD_UK = [
    "Потрібно обережно обращаться з цими інструментами",
    "Він очень втомився",
    "Я тоже іду з вами",
    "Сейчас немає часу",
    "Цей дом дуже старый",
    "Він сказал мені правду",
    # добавлено после блока 47
    "Я отримав залог за пляшку",
    "Орел хапає курицю своїм когтем",
    "будівельний підрядник, застройник",
    "Він завжди здесь",
]
GOOD_RU = [
    "Нужно осторожно обращаться с этими инструментами",
    "Он очень устал после работы",
    "Это съел кто-то другой",
]
BAD_RU = [
    "Нужно осторожно поводитися з цими інструментами",
    "Він дуже втомився",
]


def selfcheck() -> None:
    for s in GOOD_UK:
        if uk_hit(s):
            print(f"САМОПРОВЕРКА УПАЛА: ложное срабатывание на uk {s!r}")
            sys.exit(1)
    for s in BAD_UK:
        if not uk_hit(s):
            print(f"САМОПРОВЕРКА УПАЛА: пропущено uk {s!r}")
            sys.exit(1)
    for s in GOOD_RU:
        if ru_hit(s):
            print(f"САМОПРОВЕРКА УПАЛА: ложное срабатывание на ru {s!r}")
            sys.exit(1)
    for s in BAD_RU:
        if not ru_hit(s):
            print(f"САМОПРОВЕРКА УПАЛА: пропущено ru {s!r}")
            sys.exit(1)
    print(f"самопроверка: {len(GOOD_UK) + len(GOOD_RU)} правильных и "
          f"{len(BAD_UK) + len(BAD_RU)} испорченных строк разобраны верно\n")


def main() -> None:
    selfcheck()
    engine = create_engine(settings.DATABASE_URL_SYNC)
    with engine.connect() as conn:
        rows = conn.execute(text(
            "SELECT id, word_de, translation_uk, example_uk, "
            "translation_ru, example_ru FROM words ORDER BY id"
        )).all()

    found = []
    for i, w, t_uk, e_uk, t_ru, e_ru in rows:
        for col, val, probe in (("translation_uk", t_uk, uk_hit),
                                ("example_uk", e_uk, uk_hit),
                                ("translation_ru", t_ru, ru_hit),
                                ("example_ru", e_ru, ru_hit)):
            if not val:
                continue
            mark = probe(val)
            if mark:
                found.append((i, w, col, mark, val))

    print(f"прочитано рядов: {len(rows)}")
    print(f"с чужим языком внутри: {len(found)}\n")
    for i, w, col, mark, val in found:
        print(f"  {i:>6}  {w:<22} {col:<15} [{mark}]  {val}")


if __name__ == "__main__":
    main()
