"""Книжная связка «є» в украинской ячейке там, где она не нужна.

Класс попался в блоке 69 и повторился в блоке 71 пять раз:

    Я є громадянином Німеччини          → Я громадянин Німеччини
    Вона є експерткою в цій галузі      → Вона експертка в цій галузі
    Хто є власником рахунку?            → Хто власник рахунку?
    Цивільна відповідальність є важливою → ... важлива
    Вона є учницею на виробництві       → Вона учениця на виробництві

Это не ошибка грамматики: конструкция существует. Но в украинском
языке она канцелярская, калька с польского и английского, и в живой
речи связка опускается. На карточке B1 она учит неестественной фразе.

ПРИМЕТА БЕРЁТ НЕ ВСЁ «є», А ТОЛЬКО ОДНУ ЕГО ФОРМУ. Украинское «є»
многозначно, и большая часть его употреблений законна:

  • бытийное «є» — «У мене є час», «Тут є вода». Берёт именительный;
  • «є» в составе «є в/у/на» — «Німеччина є в Європейському Союзі»;
  • «є» как форма третьего лица множественного — «вони є».

Отличить книжную связку можно по падежу сказуемого: она требует
ОРУДНОГО (громадянин → громадянином, експертка → експерткою,
важлива → важливою), а бытийное «є» орудного не берёт никогда.
Поэтому примета ищет «є» + слово на `-ом/-ем/-ою/-ею`, и ничего
больше. Всё остальное «є» она не видит — и не должна.

Гейтом быть не может: в юридическом тексте связка уместна, и если
владелец захочет оставить её в канцелярских рядах, это будет его
решение, а не ошибка. Белый список по (id).

    python -m app.scripts.scan_uk_copula_je
"""

from __future__ import annotations

import re
import sys

from sqlalchemy import create_engine, text

from app.config import settings

# «є» и сразу за ним слово в орудном падеже. Орудный — единственный
# падеж, который бытийное «є» взять не может, поэтому он и служит
# признаком книжной связки.
COPULA = re.compile(r"\bє\s+\S*(ом|ем|ою|ею)\b", re.IGNORECASE)

COLUMNS = ("translation_uk", "example_uk")

# Ряды, где связка оставлена сознательно.
LEGIT: set[int] = set()

GOOD = [
    # бытийное «є» — именительный падеж, связкой не является
    "У мене є час",
    "Тут є вода",
    "У нас немає доступу, але є інтернет",
    # «є» перед предлогом — тоже не связка
    "Німеччина є в Європейському Союзі",
    "Відповідь є на останній сторінці",
    # орудный падеж без «є» — обычное управление
    "Він працює бухгалтером",
    "Вона стала експерткою в цій галузі",
    # предикатив без связки — то, к чему приметa и ведёт
    "Я громадянин Німеччини",
]
BAD = [
    "Я є громадянином Німеччини",
    "Вона є експерткою в цій галузі",
    "Хто є власником рахунку?",
    "Цивільна відповідальність є важливою",
    "Вона є учницею на виробництві",
]


def selfcheck() -> None:
    bad_good = [s for s in GOOD if COPULA.search(s)]
    good_bad = [s for s in BAD if not COPULA.search(s)]
    if bad_good or good_bad:
        print("САМОПРОВЕРКА НЕ ПРОШЛА")
        for s in bad_good:
            print(f"  ложное срабатывание: {s!r}")
        for s in good_bad:
            print(f"  не поймано: {s!r}")
        sys.exit(1)
    print(f"самопроверка: {len(GOOD)} чистых, {len(BAD)} грязных — ок\n")


def main() -> None:
    selfcheck()
    engine = create_engine(settings.DATABASE_URL_SYNC)
    cols = ", ".join(COLUMNS)
    with engine.connect() as conn:
        rows = conn.execute(
            text(f"SELECT id, word_de, {cols} FROM words ORDER BY id")
        ).all()

    hits: list[tuple[int, str, str, str]] = []
    for row in rows:
        wid, word = row[0], row[1]
        if wid in LEGIT:
            continue
        for col, val in zip(COLUMNS, row[2:]):
            if val and COPULA.search(val):
                hits.append((wid, word, col, val))

    for wid, word, col, val in hits:
        print(f"id={wid} {word} · {col}")
        print(f"  {val}")

    print(f"\nпрочитано рядов: {len(rows)}")
    print(f"в белом списке: {len(LEGIT)}")
    print(f"книжных связок: {len(hits)}")


if __name__ == "__main__":
    main()
