"""
Сопоставление текста reply-кнопок с действием.

Реплай-кнопки приходят от Telegram обычным текстом, поэтому хендлеры должны
знать все локализованные варианты надписи. Раньше эти списки были вписаны
в каждый хендлер руками (F.text.in_(["📚 Учить слова", "📚 Вчити слова", ...])) —
добавление языка интерфейса требовало правок в нескольких файлах, а расхождение
с локалью молча ломало кнопку.

Теперь варианты берутся из самих локалей: источник истины один.
"""

from aiogram import F

from app.locales import LOCALES, get_text

BTN_LEARN_WORDS = "btn_learn_words"
BTN_STATS = "btn_stats"
BTN_RATING = "btn_rating"
BTN_SETTINGS = "btn_settings"
BTN_HELP = "btn_help"


# ПОДПИСИ, КОТОРЫЕ УЖЕ УЕХАЛИ ЛЮДЯМ.
#
# Реплай-клавиатура живёт НА СООБЩЕНИИ и обновляется только когда бот
# создаёт новый якорь. Значит у всякого, кто открыл переписку до смены
# подписей, в чате остаётся прежняя клавиатура — со значками. Нажатие
# приходит её текстом, и фильтр, собранный из нынешних локалей, такого
# текста уже не знает: кнопка просто перестаёт работать.
#
# Выбраться из этого человек может только командой, которую надо знать.
# Поэтому прежние подписи перечислены здесь и остаются В ФИЛЬТРЕ, но
# нигде не показываются. Удалить их можно, когда у всех появится новый
# якорь, — то есть после того, как каждый хоть раз нажмёт что-нибудь.
#
# Список заморожен нарочно: он описывает прошлое, и обновлять его при
# следующих правках подписей НЕ НАДО — надо добавить новый такой же.
LEGACY_TEXTS: dict[str, frozenset[str]] = {
    "btn_learn_words": frozenset({
        "📚 Учить слова", "📚 Вчити слова", "📚 Learn words",
        "📚 Kelime öğren", "📚 Wörter lernen", "📚 Ucz się słów",
    }),
    "btn_stats": frozenset({
        "📊 Статистика", "📊 Statistics", "📊 İstatistik",
        "📊 Statistik", "📊 Statystyki",
    }),
    "btn_rating": frozenset({
        "🏆 Рейтинг", "🏆 Rating", "🏆 Sıralama",
        "🏆 Rangliste", "🏆 Ranking",
    }),
    "btn_settings": frozenset({
        "🦾 Настройки", "🦾 Налаштування", "🦾 Settings",
        "🦾 Ayarlar", "🦾 Einstellungen", "🦾 Ustawienia",
    }),
    "btn_help": frozenset({
        "❓ Помощь", "❓ Допомога", "❓ Help",
        "❓ Yardım", "❓ Hilfe", "❓ Pomoc",
    }),
}


def button_texts(key: str) -> set[str]:
    """
    Все надписи кнопки: нынешние из локалей и прежние, уже уехавшие людям.

    Прежние нужны только фильтру. Там, где надпись ПОКАЗЫВАЕТСЯ, берётся
    `get_text` — и показывается всегда нынешняя.
    """
    return {get_text(key, lang) for lang in LOCALES} | set(
        LEGACY_TEXTS.get(key, ())
    )


def pressed(key: str):
    """Фильтр aiogram: нажата кнопка с этим ключом на любом языке интерфейса."""
    return F.text.in_(button_texts(key))


def menu_texts() -> set[str]:
    """
    Все надписи кнопок главного меню на всех языках интерфейса.

    Нужно, чтобы обработчики, ловящие ПРОИЗВОЛЬНЫЙ текст, не съедали нажатия
    меню. Беда настоящая и уже случилась: подсказка «ответь голосом»
    подписалась на `F.text` в состоянии ответа, а роутер игры подключён
    раньше настроек и статистики — и во время вопроса эти кнопки переставали
    работать. Молча: обработчик срабатывал, ничего не делал и событие гасил.
    """
    return {
        text
        for key in (BTN_LEARN_WORDS, BTN_STATS, BTN_RATING, BTN_SETTINGS, BTN_HELP)
        for text in button_texts(key)
    }
