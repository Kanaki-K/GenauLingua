"""
Доска сопоставления: пять слов слева, пять значений справа.

ПОЧЕМУ ЭТО НЕ ЧЕТВЁРТЫЙ НАВЫК

Карточка, слух и речь — три РАЗНЫХ навыка, и шкалы на домашнем экране
измеряют именно их. Сопоставление же проверяет узнавание написанного, то
есть тот же навык, что карточка, только задачу делает ЛЕГЧЕ: из пяти пар
последняя достаётся бесплатно, предпоследняя — монеткой. Знание несут
примерно три пары из пяти.

Отсюда правило учёта, без которого шкала «написанное» начала бы расти
дёшево, а она у нас честное зеркало:

    В ПРОГРЕСС ИДУТ ТОЛЬКО ПАРЫ, СОШЕДШИЕСЯ С ПЕРВОЙ ПОПЫТКИ,
    И НИКОГДА — ПОСЛЕДНЯЯ ОСТАВШАЯСЯ.

И тот же порог допуска, что у слуха: на доску берутся слова, отвеченные
верно хотя бы раз. Новому слову исключение не учит ничему — человек найдёт
пару методом вычёркивания и не запомнит ни одной.

ОТБОР ПО ДЛИНЕ ОБЯЗАТЕЛЕН. Две колонки делят ширину экрана пополам, и в
кнопку влезает около четырнадцати знаков — из которых два забирает значок
состояния. Предел потому и двенадцать; цена и расчёт — у `LABEL_LIMIT`
ниже. Без фильтра каждое четвёртое слово поехало бы на вторую строку, и
решётка развалилась бы.
"""

from __future__ import annotations

import logging
import random
from typing import Optional

from sqlalchemy import and_, func, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.database.enums import CEFRLevel
from app.database.models import User, UserWord, Word, WordLangGroup
from app.services.language_service import LanguagePair, option_label, word_column

logger = logging.getLogger(__name__)

# Сколько пар на доске. Пять — по решению владельца.
BOARD_SIZE = 5

# Предел длины подписи. В кнопку на половину ширины экрана влезает около
# четырнадцати знаков — но ДВА из них забирает значок состояния («▸ » или
# «✓ »), и считать предел без него нельзя. Первая редакция так и считала:
# «die Tankstelle» проходило отбор ровно в четырнадцать, а сойдясь,
# становилось «✓ die Tankstelle» в шестнадцать и уезжало на вторую строку —
# ряд становился выше соседних.
#
# Замер цены этой строгости по канонической базе:
#
#     предел      A1          B1          C2       всего
#       14    1104 (89%)  2450 (78%)   891 (66%)    9 605
#       12    1009 (81%)  1974 (63%)   653 (48%)    7 672
#       10     829 (67%)  1270 (40%)   344 (25%)    4 931
#
# Двенадцать стоят пятой части словаря, и это по делу: доске из пяти пар
# хватает и 653 слов C2 — это сто тридцать разных досок. А десять уже режут
# по живому.
LABEL_LIMIT = 12

# Сколько верных ответов по слову нужно, чтобы пустить его на доску. Один —
# тот же порог, что у вопроса на слух, и по той же причине: нельзя узнать
# то, чего ни разу не видел, а вычёркиванием человек найдёт пару и не
# запомнит её.
UNLOCK_CORRECT = 1

# Сколько слов тянуть из базы, чтобы отобрать пять. С запасом: отсев по
# длине идёт уже в Python — она считается по ВЫБРАННОМУ значению, а не по
# ячейке, и в SQL это условие не выразить.
CANDIDATES = 120


async def pick_words(
    user: User,
    session: AsyncSession,
    pair: LanguagePair,
    level: Optional[CEFRLevel] = None,
    size: int = BOARD_SIZE,
) -> list[Word]:
    """
    Слова для доски: знакомые, с короткими подписями, в случайном порядке.

    НАБОР СЛОВ — ТОТ ЖЕ, ЧТО У КРУГА: решение владельца, и оно верное.
    Отбор идёт через `_apply_quiz_mode_filter` — ту же функцию, которой
    пользуется сам генератор вопросов. Значит уровень соблюдается в режиме
    «по уровню», категория в режиме «по категории», а в «топ-10 тысяч»
    границ нет.

    Своего фильтра здесь нарочно НЕТ. Первая редакция смотрела только на
    уровень: `level if quiz_mode is LEVEL else None` — и в режиме «по
    категории» доска молча расширялась на всю базу, а в «сложных» брала
    что попало. Три места, решающих «какие слова учит этот человек»,
    разошлись бы при первой же правке режимов — ровно как разошлись три
    списка роутеров.

    `level` остаётся отдельным параметром для проверок: он сужает набор
    поверх режима, не заменяя его.

    Возвращает меньше `size`, если подходящих не нашлось — решать, хватает
    ли их на доску, предоставлено вызывающему: неполная доска это не ошибка
    данных, а честный ответ «ещё рано».
    """
    from app.services.quiz_service import _apply_quiz_mode_filter
    # Колонки берутся по НАПРАВЛЕНИЮ: в обратном режиме вопрос задаётся
    # на языке значения, и пустая ячейка там так же непригодна
    prompt_col = word_column(pair.prompt_lang)
    answer_col = word_column(pair.answer_lang)

    query = (
        select(Word)
        .join(
            WordLangGroup,
            and_(
                WordLangGroup.word_id == Word.id,
                WordLangGroup.lang == pair.learning,
                WordLangGroup.is_canonical.is_(True),
            ),
        )
        .join(
            UserWord,
            and_(
                UserWord.word_id == Word.id,
                UserWord.user_id == user.id,
                UserWord.learning_lang == pair.learning,
            ),
        )
        .where(
            UserWord.times_correct >= UNLOCK_CORRECT,
            prompt_col.isnot(None),
            func.btrim(prompt_col) != "",
            answer_col.isnot(None),
            func.btrim(answer_col) != "",
        )
    )

    # Режим человека — тем же фильтром, что у генератора вопросов
    query = _apply_quiz_mode_filter(query, user)
    if level is not None:
        query = query.where(Word.level == level)

    query = query.order_by(func.random()).limit(CANDIDATES)
    candidates = (await session.execute(query)).scalars().all()

    picked: list[Word] = []
    seen_labels: set[tuple[str, str]] = set()
    for word in candidates:
        left = option_label(word, pair.prompt_lang)
        right = option_label(word, pair.answer_lang)
        if not left or not right:
            continue
        if len(left) > LABEL_LIMIT or len(right) > LABEL_LIMIT:
            continue
        # Повтор подписи сделал бы доску неразрешимой: две одинаковые
        # кнопки справа означают, что верных ответов два, а засчитан будет
        # один. Сверяются ОБЕ стороны: совпасть может любая
        key = (left.casefold(), right.casefold())
        if key in seen_labels:
            continue
        if any(left.casefold() == l or right.casefold() == r
               for l, r in seen_labels):
            continue
        seen_labels.add(key)
        picked.append(word)
        if len(picked) == size:
            break

    return picked


# Самый короткий круг, в который доску ещё можно вставить. Десять — потому
# что доска занимает пять слотов: в круге из десяти это половина, и меньше
# уже не круг с разминкой, а разминка с довеском.
MIN_ROUND_FOR_BOARD = 10


def board_slots(round_length: int, size: int = BOARD_SIZE) -> tuple[int, int]:
    """
    С какого по какой вопрос круга занимает доска. Нумерация с единицы.

    СЕРЕДИНА, и это выбрано по замеру, а не на вкус.

    Не начало: 9.5% кругов закрываются, не ответив НИ НА ОДИН вопрос, и
    встречать человека незнакомым экраном — худшее, что можно сделать с
    этой цифрой. К тому же правило проекта гласит, что первый вопрос круга
    всегда текстовый.

    Не конец: круг кончается итогом, и доска со своим итогом вклинилась бы
    между последним вопросом и результатом.

    Для круга из пятнадцати выходит с шестого по десятый.
    """
    start = (round_length - size) // 2 + 1
    return start, start + size - 1


def should_insert_board(user: User, round_length: int, eligible: int) -> bool:
    """
    Вставлять ли доску в этот круг.

    Три условия, и каждое по делу:

    * человек её не выключил;
    * круг достаточно длинный — иначе доска съест половину;
    * годных слов ВДВОЕ больше доски. Ровно пяти мало: доски пошли бы
      одним и тем же набором, и упражнение превратилось бы в заучивание
      расположения кнопок;
    * ЧЕРЕЗ КРУГ, по чётности числа пройденных. Каждый круг — треть
      занятия всегда одно и то же; «раз в N» потребовало бы счётчика,
      который негде хранить и который разъедется. Чётность бесплатна,
      детерминированна и объяснима.
    """
    if not getattr(user, "match_in_round", True):
        return False
    if round_length < MIN_ROUND_FOR_BOARD:
        return False
    if eligible < BOARD_SIZE * 2:
        return False
    return (user.quizzes_passed or 0) % 2 == 0


def deranged_order(size: int, rng: Optional[random.Random] = None) -> list[int]:
    """
    Порядок правой колонки: перестановка БЕЗ неподвижных точек.

    Требование владельца дословно: «они стоят не очевидно друг к другу».
    Обычного перемешивания для этого мало — у случайной перестановки пяти
    элементов в среднем один остаётся на своём месте, и тогда пара стоит
    ровно напротив себя, то есть подсказана. Вероятность, что хотя бы один
    совпадёт, около 63%: на двух досках из трёх человек получал бы готовый
    ответ.

    Поэтому перестановка перемешивается заново, пока неподвижных точек не
    останется. Для пяти элементов это пара попыток, а дешёвого способа
    построить её напрямую нет.
    """
    rng = rng or random
    order = list(range(size))
    if size < 2:
        return order

    for _ in range(100):
        rng.shuffle(order)
        if all(position != index for position, index in enumerate(order)):
            return order

    # Сто неудач подряд невозможны даже теоретически, но возвращать
    # подсказанную доску нельзя: сдвигаем на один, и совпадений нет по
    # построению
    logger.warning("перемешивание не дало перестановки без совпадений")
    return order[1:] + order[:1]


def scored_pairs(first_try: set[int], matched_order: list[int]) -> set[int]:
    """
    Какие пары идут в прогресс. Принимает порядок, в котором они сходились.

    Два отсева, и оба обязательны:

    * только сошедшиеся С ПЕРВОЙ ПОПЫТКИ. Пара, найденная после промаха, —
      это не узнавание, а перебор;
    * никогда ПОСЛЕДНЯЯ СОШЕДШАЯСЯ. Когда остаётся одна пара, нажать
      больше не во что: засчитать её значило бы платить за отсутствие
      выбора. Поэтому и нужен порядок — какая пара оказалась последней,
      видно только по нему, а не по номерам на доске.

    На доске из одной пары не засчитывается ничего: бесплатна она же.
    """
    if len(matched_order) < 2:
        return set()
    return set(first_try) - {matched_order[-1]}
