# -*- coding: utf-8 -*-
"""
Повод вернуться: что сказать в напоминании, чтобы это было правдой.

ЗАЧЕМ. Напоминание — единственный экран, который человек видит, НЕ заходя
в бота, и единственный рычаг против главной беды проекта: 79% не
возвращались на второй день. А вторым блоком в нём стояла случайная фраза
из шести:

    «Шаг за шагом ты достигаешь результата!»
    «Твоя серия растёт — продолжай в том же духе!»
    «Ты на правильном пути! Не останавливайся!»

Ни одна ничего не знает о человеке. Хуже: фраза про растущую серию
показывалась ровно тогда, когда показывать было нечего — блок выбирался
«шкалы ИЛИ подбадривание», то есть доставался человеку БЕЗ прогресса и
без серии. Бот сообщал о росте серии тому, у кого её нет.

УСТРОЙСТВО ТО ЖЕ, ЧТО У ПООЩРЕНИЯ. Факты измеряются, правило выбирает
ОДИН повод — самый действенный из применимых, — и каждый повод обязан
быть правдой на момент отправки. Разница в сути: поощрение говорит о том,
что УЖЕ случилось, напоминание — о том, что ЖДЁТ.

ПОЧЕМУ «СЛОВА ЖДУТ ПОВТОРЕНИЯ» СИЛЬНЕЕ ЛЮБОЙ ФРАЗЫ. Это не похвала и не
призыв, а сообщение о деле: сроки повторения бот считает сам, и к утру
часть слов просрочена. Число меняется каждый день само — значит и строка
меняется, без набора бодрых заготовок.

ПОПРАВКА ПО ЗАМЕРУ. В первой редакции семи поводов стояло «118 слов
выучено, до 120 — два». У 156 человек из 199 «выучено» — ноль, и такое
напоминание не пришло бы им никогда. Все рубежи считаются по СЛОВАМ В
РАБОТЕ; «выучено» осталось отдельным редким поводом — «первое близко».
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

from app.services.praise_service import MILESTONES, next_milestone

# Серия считается живой с двух дней: один день — это не серия, и
# «не прерывай» при единице было бы призывом не прерывать то, чего нет.
STREAK_ALIVE = 2

# Насколько близко рубеж, чтобы о нём стоило говорить. Десять слов — это
# примерно один круг, то есть обещание выполнимо сегодня же.
MILESTONE_CLOSE = 10

# Сколько просроченных слов превращают «повторить» в «многовато». Длинный
# перерыв даёт двести просроченных слов, и число в такой строке не звало
# бы, а придавливало.
DUE_MANY = 50

# Сколько дней молчания делают возврат отдельным поводом.
AWAY_LONG = 7

# Сколько людей должно быть в зачёте по языку, чтобы место что-то значило.
RANK_MIN_FIELD = 5

# Полезные замечания на случай, когда поводов нет вовсе: у новичка их и не
# может быть. Это не подбадривание, а то, чего человек про бота не знает.
FACTS_COUNT = 4


@dataclass(frozen=True)
class ReminderFacts:
    """Что известно о человеке к моменту отправки. Только числа."""
    due_words: int = 0           # слов просрочено по расписанию повторения
    streak_days: int = 0
    best_streak: int = 0
    active_today: bool = False   # сегодня уже занимался
    words_in_work: int = 0
    learned: int = 0
    almost_learned: int = 0      # до «выучено» остался один верный ответ
    rank: int = 0
    rank_field: int = 0          # сколько людей в зачёте по этому языку
    rounds_total: int = 0
    days_away: int = 0
    # Сколько новых слов принесёт ближайший круг. None — не замерено (так
    # строят факты проверки правила); напоминание замеряет всегда
    new_next_round: Optional[int] = None


def pick_reason(facts: ReminderFacts) -> tuple[str, dict]:
    """
    Один повод вернуться — самый действенный из применимых.

    ПОРЯДОК — ПО РЕДКОСТИ, А НЕ ПО СИЛЕ. Так же, как в поощрении за круг,
    и по той же причине: частый повод, стоящий выше редкого, делает редкий
    МЁРТВЫМ. Это выяснилось не чтением кода, а приёмкой на живых данных:

        remind_due достаётся 140 людям из 233, а просроченные слова есть
        почти у каждого, кто вообще играл. Стоя третьим, «слова ждут»
        перекрывало «до первого выученного — один ответ», «лучшая серия
        была 9 дней» и «место в зачёте»: НИ ОДИН из трёх не достался
        никому на всей базе.

    Отсюда порядок:

      серия под угрозой   истекает СЕГОДНЯ, другого шанса не будет
      первое выученное    у 156 человек из 199 его не было ни разу
      серия оборвалась    пока потеря свежа — окно в неделю
      рубеж близко        обещание, выполнимое за один круг
      слова ждут          дело; есть почти у всех, потому и ниже
      место в зачёте      слабее дела, но хоть с кем-то сравнивает
      замечание о боте    когда поводов нет: у новичка их и не может быть

    Повод возвращается всегда: напоминание без второй строки — это голое
    «пора заниматься», от которого человек и отписывается.
    """
    if facts.streak_days >= STREAK_ALIVE and not facts.active_today:
        return "remind_streak_risk", {"days": facts.streak_days}

    if facts.learned == 0 and facts.almost_learned > 0:
        return "remind_almost_learned", {"count": facts.almost_learned}

    # Окно нарочно: «лучшая серия была 9 дней» работает, пока потеря
    # свежа. Через месяц молчания это уже не подгоняет, а упрекает, и
    # человеку полезнее услышать, что накопилось дело.
    if (facts.streak_days == 0 and facts.best_streak >= 3
            and STREAK_ALIVE <= facts.days_away <= AWAY_LONG):
        return "remind_streak_lost", {"days": facts.best_streak}

    # Рубеж — только когда есть что двигать. При нуле слов строка выходила
    # «Слов в работе: 0 · до 10 ещё 10», то есть той самой шкалой-нулём, от
    # которой и уходили: ноль в лицо вместо повода
    #
    # «Это один круг» — обещание, и держит его только состав круга: новых в
    # нём три, если повторять есть что. Замер 14 октября: у 12 человек из 72,
    # получавших этот повод, рубеж кругом был недостижим (44 просроченных,
    # 3 новых за круг, до рубежа 6). Такой человек повод не получает — ему
    # честнее «слова ждут»
    target = next_milestone(facts.words_in_work)
    if (facts.words_in_work > 0 and target is not None
            and target - facts.words_in_work <= MILESTONE_CLOSE
            and (facts.new_next_round is None
                 or target - facts.words_in_work <= facts.new_next_round)):
        return "remind_milestone_close", {
            "count": facts.words_in_work,
            "target": target,
            "left": target - facts.words_in_work,
        }

    if facts.due_words > DUE_MANY:
        return "remind_due_many", {}
    if facts.due_words > 0:
        return "remind_due", {"count": facts.due_words}

    if facts.rank and facts.rank_field >= RANK_MIN_FIELD:
        return "remind_rank", {"rank": facts.rank, "total": facts.rank_field}

    # Замечание выбирается по числу пройденных кругов, а не случайно:
    # так оно меняется по мере занятий и ОДИНАКОВО воспроизводится в
    # проверке — случайность пришлось бы подменять заглушкой
    index = facts.rounds_total % FACTS_COUNT + 1
    return f"remind_fact_{index}", {}


def reason_line(facts: ReminderFacts, lang: Optional[str], seed: int = 0) -> str:
    """
    Готовая строка повода. Повод — правилом, СЛОВА — по кругу (`rotated`):
    тот же повод изо дня в день звучит по-разному (патч 2.1).
    """
    from app.locales import get_text, rotated

    key, params = pick_reason(facts)
    return get_text(rotated(key, seed), lang, **params)


__all__ = [
    "AWAY_LONG", "DUE_MANY", "FACTS_COUNT", "MILESTONES", "MILESTONE_CLOSE",
    "RANK_MIN_FIELD", "STREAK_ALIVE", "ReminderFacts", "pick_reason",
    "reason_line",
]
