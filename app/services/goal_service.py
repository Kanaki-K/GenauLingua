"""
Зачем человек учит язык — и какие слова из этого следуют.

ЗАМЕР, ИЗ-ЗА КОТОРОГО ЭТО ПОНАДОБИЛОСЬ

Двадцать категорий в базе есть, режим «по категории» работает — и им
пользуются ТРИ человека из 233. Не потому, что он плох, а потому, что
спрятан: режим викторины лежит третьим уровнем настроек, и 223 человека из
233 не меняли его ни разу. Выбор — это работа, и её не делают.

Значит, выбрать надо за человека. Это тот случай, когда так правильно:
вопрос задаётся один, ответ занимает одно нажатие, и это НЕ ДОБАВЛЯЕТ
шага — кнопка, которой человек всё равно начинает первый круг, просто
заодно говорит, зачем он здесь.

ПОЧЕМУ ЦЕЛЬ НЕ ПЕРЕКЛЮЧАЕТ РЕЖИМ НА «ПО КАТЕГОРИИ»

Соблазн был: цель → категория → `QuizMode.CATEGORY`, и ни строчки нового
кода. Замер отменил: режим CATEGORY не смотрит на уровень ВОВСЕ, и
новичок, выбравший «для работы», получал бы слова C1 вперемешку с A1.
А наоборот, с уровнем вместе, многие пары попросту пусты:

    Wirtschaft        142 слова, из них A1 — ДВА
    Wissenschaft      193 слова, из них A1 — четыре
    Technik & Digital 291 слово,  из них A1 — двенадцать

Поэтому цель ПОДМЕШИВАЕТ тему в новые слова, а трудность по-прежнему
задаёт уровень. Кончились слова темы — берём любые: пустой круг хуже
нетематического.
"""

from __future__ import annotations

from typing import Optional

from app.database.enums import WordCategory

# Цель → категории, из которых брать новые слова.
#
# Разложение спорное и будет правиться — потому цель и хранится в базе, а
# сопоставление живёт здесь: поправить таблицу дешевле, чем переписывать
# данные людей.
#
# По три категории на цель: одна даёт слишком узкий поток (и у половины
# целей упёрлась бы в десяток слов уровня), пять перестают быть темой.
GOAL_CATEGORIES: dict[str, tuple[WordCategory, ...]] = {
    "work": (
        WordCategory.ARBEIT_BERUF,
        WordCategory.WIRTSCHAFT,
        WordCategory.KOMMUNIKATION,
    ),
    "travel": (
        WordCategory.REISEN_TRANSPORT,
        WordCategory.ESSEN_TRINKEN,
        WordCategory.ZEIT_ALLTAG,
    ),
    # Переезд — это не путешествие: тут не меню и расписание, а врач,
    # договор аренды и ведомство
    "living": (
        WordCategory.RECHT_STAAT,
        WordCategory.WOHNEN_HAUS,
        WordCategory.GESUNDHEIT_MEDIZIN,
    ),
    "study": (
        WordCategory.BILDUNG_LERNEN,
        WordCategory.WISSENSCHAFT,
        WordCategory.GRAMMATIK,
    ),
    # «Просто слова» — честный ответ, а не отказ отвечать. Он хранится
    # наравне с остальными: иначе не отличить человека, который выбрал не
    # выбирать, от того, кого ещё не спрашивали.
    "any": (),
}

# Ключи надписей кнопок, в порядке показа. «Просто слова» последним: он
# запасной, и стоять первым ему незачем.
GOAL_ORDER = ("work", "travel", "living", "study", "any")


def is_goal(code: str) -> bool:
    return code in GOAL_CATEGORIES


def categories_for(goal: Optional[str]) -> tuple[str, ...]:
    """
    Значения категорий для цели. Пустой кортеж — темы нет, берём любые слова.

    Возвращаются ЗНАЧЕНИЯ, а не члены перечисления: в базе лежит строка
    («Arbeit & Beruf»), и сравнивать надо с ней.
    """
    if not goal:
        return ()
    return tuple(c.value for c in GOAL_CATEGORIES.get(goal, ()))
