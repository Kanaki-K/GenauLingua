"""
Серия дней занятий: одно место, которое знает о ней всё.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Серия — главный мотиватор в боте: она стоит на
домашнем экране, в напоминании, в статистике, в админке и в месячном
зачёте. При этом до 13 октября 2026 её ВЫЧИСЛЯЛ один обработчик, а ЧИТАЛИ
пятеро — каждый напрямую из колонки `users.streak_days`. И колонка врала.

ЧТО БЫЛО НЕ ТАК. Серия пересчитывается только когда человек заканчивает
круг. Значит у того, кто перестал заниматься, в колонке навсегда остаётся
последнее значение. Замер по рабочей копии:

    людей с непустой серией                    128
    из них серия УСТАРЕЛА                     128   (все до единого)
    последняя активность                2026-02-19   (236 дней назад)

То есть домашний экран и напоминание говорили «1 день подряд» человеку,
который не заходил восемь месяцев. Для экрана, который должен мотивировать,
это худший вид вранья: он хвалит за то, чего нет, и человек перестаёт
верить остальным числам.

РЕШЕНИЕ. Серия считается ПО ДАТЕ, а не читается из колонки. Колонка
остаётся хранилищем, но наружу её отдаёт `current_streak`, который знает
про срок годности.

ДЕНЬ — ЭТО ДЕНЬ ЧЕЛОВЕКА, А НЕ UTC. До 14 октября 2026 день занятий брался
по UTC, хотя у каждого человека в базе записан часовой пояс (`timezone`, по
умолчанию Europe/Berlin — 231 из 233). Для Берлина летом это два часа
сдвига, и серия врала в обе стороны:

    пн 01:30 и вт 23:30 по Берлину   два дня подряд  → серия 1 (оборвана)
    пн 23:30 и СР 00:30 по Берлину   вторник пропущен → серия 2 (выдумана)

Оба случая воспроизведены исполнением. Теперь день человека даёт
`user_today` / `user_day`, и через них идут отметка дня, чтение серии,
`last_quiz_date` и месячная серия.
"""

from __future__ import annotations

import re
from datetime import date, datetime, timedelta, timezone
from typing import Optional
from zoneinfo import ZoneInfo

from app.core.clock import utcnow

# Пояс по умолчанию — тот же, что у колонки `users.timezone`. Нужен, когда
# у человека пояс не записан вовсе или записан неизвестной строкой.
DEFAULT_TIMEZONE = "Europe/Berlin"

_OFFSET = re.compile(r"^([+-])(\d{1,2}):?(\d{2})?$")


# ============================================================================
# ПЕРЕХОД С UTC НА МЕСТНЫЙ ДЕНЬ
# ============================================================================
#
# Серии у людей уже посчитаны по UTC, и переход не должен оборвать ни одну.
# Опасный случай один и односторонний: у пояса восточнее UTC (это все люди
# в базе) день, записанный по UTC, бывает на сутки РАНЬШЕ местного. Круг в
# понедельник 01:30 по Берлину записан воскресеньем; если человек придёт во
# вторник уже по местному счёту, разрыв «вс → вт» выглядит как пропуск,
# хотя по-местному это «пн → вт».
#
# Поэтому ДОПУСК: день, записанный ДО перехода (то есть раньше
# `LOCAL_DAYS_FROM`), продолжает серию и через один день — но только когда
# сегодняшний день уже местный (не раньше `LOCAL_DAYS_FROM`). Допуск
# одноразовый по устройству: через три дня после перехода записанных по UTC
# дней с разрывом в два не остаётся. Цена — один пропущенный день,
# прощённый на переходе; это лучше, чем оборвать серию тому, кто её не
# прерывал.
#
# ДАТА ДОЛЖНА СОВПАСТЬ С ВЫКАТКОЙ на рабочий бот. Всё, что записано раньше
# неё, считается записанным по UTC — так же думают приёмка
# `audit_accounting` и починка `repair_accounting`, читая историю занятий.
# Выкатили позже — сдвинуть эту дату на день выкатки.
LOCAL_DAYS_FROM = date(2026, 10, 14)


def _zone(user):
    """Пояс человека: `timezone` → `utc_offset` → пояс проекта."""
    name = getattr(user, "timezone", None)
    if name:
        try:
            return ZoneInfo(name)
        except Exception:
            pass

    offset = getattr(user, "utc_offset", None)
    match = _OFFSET.match(offset.strip()) if offset else None
    if match:
        sign, hours, minutes = match.groups()
        delta = timedelta(hours=int(hours), minutes=int(minutes or 0))
        return timezone(-delta if sign == "-" else delta)

    return ZoneInfo(DEFAULT_TIMEZONE)


def user_day(user, moment: datetime) -> date:
    """
    Какой день был у человека в момент `moment`.

    `moment` — наивное UTC, как все отметки времени в схеме (`utcnow()`,
    `completed_at`). Для момента до `LOCAL_DAYS_FROM` возвращается день по
    UTC: так он и был записан, и история обязана читаться тем же правилом,
    каким писалась, — иначе приёмка и починка видели бы расхождение там,
    где его нет.
    """
    if moment.date() < LOCAL_DAYS_FROM:
        return moment.date()
    return moment.replace(tzinfo=timezone.utc).astimezone(_zone(user)).date()


def user_today(user, now: Optional[datetime] = None) -> date:
    """Какой сегодня день у человека. Единственный источник «сегодня» для серии."""
    return user_day(user, now or utcnow())


def _gap_allowed(last: date, today: date) -> int:
    """Сколько дней разрыва ещё продолжает серию: 1, а на переходе — 2."""
    if last < LOCAL_DAYS_FROM <= today:
        return 2
    return 1


def next_streak(streak: int, last: Optional[date], today: date) -> int:
    """
    Серия после занятия в день `today`, если прежнее было в день `last`.

    Одно правило на всех: отметка дня у человека и месячная серия в зачёте
    прежде считали каждая по-своему.
    """
    streak = int(streak or 0)
    if last is None:
        return 1
    gap = (today - last).days
    if gap <= 0:
        return max(streak, 1)
    if gap <= _gap_allowed(last, today):
        return streak + 1
    return 1


# ============================================================================
# ЗАМОРОЗКА — патч 2.1
# ============================================================================
#
# Один пропущенный день в неделю прощается: серия продолжается, день
# заморозки запоминается (`users.streak_freeze_on`). Следующая — не раньше
# чем через семь дней. Пропущено два дня и больше — серия заново, как прежде.
#
# ПОЧЕМУ В ПРАВИЛЕ, А НЕ РЯДОМ. Серию по истории занятий восстанавливают
# приёмка (`audit_accounting`) и починка (`repair_accounting`). Заморозка —
# чистая функция дат: какой день пропущен и когда прощали прошлый — видно из
# той же истории, и все трое считают одно и то же через `advance`.
#
# Месячная серия в рейтинге заморозки НЕ знает (`next_streak`): она входит
# в баллы сезона, и менять их счёт посреди месяца было бы нечестно.
FREEZE_EVERY_DAYS = 7

# С КАКОГО ДНЯ ДЕЙСТВУЕТ ЗАМОРОЗКА — день выкатки 2.1. Раньше пропуск рвал
# серию, и история обязана читаться тем правилом, каким писалась: без этой
# даты приёмка восстановила бы по старой истории «воскресшие» серии (на
# рабочей копии 15.10 — 6 человек из 128) и расходилась бы с записанным.
# ДАТА — ДЕНЬ ПОСЛЕ ВЫКАТКИ 2.1 на рабочий бот. Не день выкатки: утренние
# занятия того дня старый код уже засчитал без заморозки, и приёмка через
# `advance` «воскресила» бы их серии (независимая проверка 2.1).
FREEZE_FROM = date(2026, 10, 17)


def _freeze_ready(last_freeze: Optional[date], today: date) -> bool:
    """Можно ли простить пропуск сегодня: прошлая заморозка — неделю назад и раньше."""
    if today < FREEZE_FROM:
        return False
    return last_freeze is None or (today - last_freeze).days >= FREEZE_EVERY_DAYS


def advance(
    streak: int, last: Optional[date], today: date, last_freeze: Optional[date] = None,
) -> tuple[int, Optional[date], bool]:
    """
    Серия после занятия в день `today` — с заморозкой.

    Возвращает (серия, день последней заморозки, заморозка сработала сейчас).
    Без пропуска — ровно `next_streak`.
    """
    streak = int(streak or 0)
    if last is not None:
        gap = (today - last).days
        if gap > _gap_allowed(last, today) and gap == 2 and _freeze_ready(last_freeze, today):
            return streak + 1, today, True
    return next_streak(streak, last, today), last_freeze, False


def current_streak(user, today: Optional[date] = None) -> int:
    """
    Серия, какая она СЕЙЧАС. Ноль, если прервана.

    Серия жива, пока последний день занятий — сегодня или вчера. «Вчера»
    входит нарочно: человек, занимавшийся вечером, утром следующего дня
    ещё не прервал её, и показывать ему ноль было бы несправедливо — он
    как раз успевает её продолжить.

    Позавчера и раньше — серия прервана, и число ноль. Прежнее значение из
    колонки при этом не стирается: его хранит `best_streak_days`, а сама
    колонка перезапишется при следующем занятии.
    """
    streak = int(getattr(user, "streak_days", 0) or 0)
    if streak <= 0:
        return 0

    last = getattr(user, "last_active_date", None)
    if last is None:
        # Серия есть, а дня нет — данные старше колонки с датой. Считать
        # такую серию живой нельзя: проверить нечем
        return 0

    today = today or user_today(user)
    gap = (today - last).days
    if gap <= _gap_allowed(last, today):
        return streak
    # Вчера пропустил, а заморозка свободна — серия жива, пока он успевает
    # позаниматься сегодня: занятие её и продолжит (`advance`)
    if gap == 2 and _freeze_ready(getattr(user, "streak_freeze_on", None), today):
        return streak
    return 0


def register_activity(user, today: Optional[date] = None) -> int:
    """
    Отметить день занятий и вернуть серию после отметки.

    ЛУЧШАЯ СЕРИЯ ВЕДЁТСЯ ЗДЕСЬ ЖЕ. Колонка `best_streak_days` существовала
    с самого начала и не записывалась НИ РАЗУ: ноль у всех 233 человек.
    Между тем это единственное число, которое у прервавшего серию
    остаётся, — и единственное, что можно показать вместо обнулённой
    серии: «лучшее — 12 дней подряд» звучит иначе, чем «0 дней подряд».

    Правило продолжения: сегодня — ничего не меняется (день уже отмечен),
    вчера — серия растёт, раньше — начинается заново с единицы.

    `last_quiz_date` пишется ЗДЕСЬ ЖЕ и тем же днём. Завершение круга ставит
    её раньше по UTC; отметка дня идёт после и перезаписывает её местным
    днём, чтобы у одного занятия не было двух разных «сегодня».
    """
    today = today or user_today(user)
    last = getattr(user, "last_active_date", None)

    if last == today:
        if hasattr(user, "last_quiz_date"):
            user.last_quiz_date = today
        return int(user.streak_days or 0)

    user.streak_days, freeze_on, _ = advance(
        user.streak_days, last, today, getattr(user, "streak_freeze_on", None)
    )
    if hasattr(user, "streak_freeze_on"):
        user.streak_freeze_on = freeze_on
    user.last_active_date = today
    if hasattr(user, "last_quiz_date"):
        user.last_quiz_date = today
    user.best_streak_days = max(
        int(getattr(user, "best_streak_days", 0) or 0), int(user.streak_days)
    )
    return int(user.streak_days)
