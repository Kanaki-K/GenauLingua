"""
Серия дней занятий: одно место, которое знает о ней всё.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Серия — главный мотиватор в боте: она стоит на
домашнем экране, в напоминании, в статистике, в админке и в месячном
зачёте. При этом до 13 октября 2026 её ВЫЧИСЛЯЛ один обработчик, а ЧИТАЛИ
пятеро — каждый напрямую из колонки `users.streak_days`. И колонка врала.

ЧТО БЫЛО НЕ ТАК. Серия пересчитывается только когда человек заканчивает
круг. Значит у того, кто перестал заниматься, в колонке навсегда остаётся
последнее значение. Замер по рабочей копии:

    людей с непустой серией                    128
    из них серия УСТАРЕЛА                     128   (все до единого)
    последняя активность                2026-02-19   (236 дней назад)

То есть домашний экран и напоминание говорили «1 день подряд» человеку,
который не заходил восемь месяцев. Для экрана, который должен мотивировать,
это худший вид вранья: он хвалит за то, чего нет, и человек перестаёт
верить остальным числам.

РЕШЕНИЕ. Серия считается ПО ДАТЕ, а не читается из колонки. Колонка
остаётся хранилищем, но наружу её отдаёт `current_streak`, который знает
про срок годности.
"""

from __future__ import annotations

from datetime import date, timedelta
from typing import Optional

from app.core.clock import utctoday


def current_streak(user, today: Optional[date] = None) -> int:
    """
    Серия, какая она СЕЙЧАС. Ноль, если прервана.

    Серия жива, пока последний день занятий — сегодня или вчера. «Вчера»
    входит нарочно: человек, занимавшийся вечером, утром следующего дня
    ещё не прервал её, и показывать ему ноль было бы несправедливо — он
    как раз успевает её продолжить.

    Позавчера и раньше — серия прервана, и число ноль. Прежнее значение из
    колонки при этом не стирается: его хранит `best_streak_days`, а сама
    колонка перезапишется при следующем занятии.
    """
    streak = int(getattr(user, "streak_days", 0) or 0)
    if streak <= 0:
        return 0

    last = getattr(user, "last_active_date", None)
    if last is None:
        # Серия есть, а дня нет — данные старше колонки с датой. Считать
        # такую серию живой нельзя: проверить нечем
        return 0

    today = today or utctoday()
    return streak if last >= today - timedelta(days=1) else 0


def register_activity(user, today: Optional[date] = None) -> int:
    """
    Отметить день занятий и вернуть серию после отметки.

    ЛУЧШАЯ СЕРИЯ ВЕДЁТСЯ ЗДЕСЬ ЖЕ. Колонка `best_streak_days` существовала
    с самого начала и не записывалась НИ РАЗУ: ноль у всех 233 человек.
    Между тем это единственное число, которое у прервавшего серию
    остаётся, — и единственное, что можно показать вместо обнулённой
    серии: «лучшее — 12 дней подряд» звучит иначе, чем «0 дней подряд».

    Правило продолжения: сегодня — ничего не меняется (день уже отмечен),
    вчера — серия растёт, раньше — начинается заново с единицы.
    """
    today = today or utctoday()
    last = getattr(user, "last_active_date", None)

    if last == today:
        return int(user.streak_days or 0)

    if last == today - timedelta(days=1):
        user.streak_days = int(user.streak_days or 0) + 1
    else:
        user.streak_days = 1

    user.last_active_date = today
    user.best_streak_days = max(
        int(getattr(user, "best_streak_days", 0) or 0), int(user.streak_days)
    )
    return int(user.streak_days)
