def main() -> None:
    apply_mode = "--apply" in sys.argv
    engine = create_engine(settings.DATABASE_URL_SYNC)

    ok, skipped, missing = [], [], []
    with engine.connect() as conn:
        for wid, col, was, now, why in FIXES:
            current = conn.execute(
                text(f"SELECT {col} FROM words WHERE id = :i"), {"i": wid}
            ).scalar()
            if current is None:
                missing.append((wid, col, "строки нет в базе"))
            elif current.strip() != was:
                skipped.append((wid, col, current))
            else:
                ok.append((wid, col, was, now, why))

    print(f"=== правок в списке: {len(FIXES)} ===")
    print(f"  совпало с базой:   {len(ok)}")
    print(f"  база изменилась:   {len(skipped)}")
    print(f"  строки нет:        {len(missing)}")
    print()

    for wid, col, was, now, why in ok:
        print(f"  {wid} {col} — {why}")
        print(f"      было:  {was}")
        print(f"      стало: {now}")

    if skipped:
        print("\n--- пропущено, в базе уже другое ---")
        for wid, col, current in skipped:
            print(f"  {wid} {col}: сейчас {current!r}")

    if missing:
        print("\n--- не найдено ---")
        for wid, col, why in missing:
            print(f"  {wid} {col}: {why}")

    if not apply_mode:
        print(f"\nэто показ. Для применения — флаг --apply")
        return

    with engine.begin() as conn:
        for wid, col, _, now, _ in ok:
            conn.execute(text(f"UPDATE words SET {col} = :v WHERE id = :i"),
                         {"v": now, "i": wid})
    print(f"\nприменено: {len(ok)}")

    # Самопроверка: ни одной правки не должно остаться неприменённой
    with engine.connect() as conn:
        left = 0
        for wid, col, was, now, _ in ok:
            cur = conn.execute(text(f"SELECT {col} FROM words WHERE id = :i"),
                               {"i": wid}).scalar()
            if (cur or "").strip() != now:
                print(f"  ТРЕВОГА: {wid} {col} не записалось")
                left += 1
        print(f"самопроверка: не записалось {left}")


if __name__ == "__main__":
    main()
