from __future__ import annotations

import sys

from sqlalchemy import create_engine, text

from app.config import settings

WHY = "пример диктовал IBAN на 22 знака: клип 10–14 с, слово в цифрах тонет"

FIXES: list[tuple[int, str, str, str, str]] = [
    (10021, "example_de",
     "Meine IBAN ist DE75512108001234567890",
     "Bitte schicken Sie mir Ihre IBAN", WHY),
    (10021, "example_en",
     "My IBAN is DE75512108001234567890",
     "Please send me your IBAN", WHY),
    (10021, "example_ru",
     "Мой IBAN — DE75512108001234567890",
     "Пришлите мне, пожалуйста, ваш IBAN", WHY),
    (10021, "example_uk",
     "Мій IBAN — DE75512108001234567890",
     "Надішліть мені, будь ласка, ваш IBAN", WHY),
    (10021, "example_tr",
     "IBAN'ım DE75512108001234567890",
     "Lütfen bana IBAN'ınızı gönderin", WHY),
    (10021, "example_pl",
     "Mój numer IBAN to DE75512108001234567890",
     "Proszę przesłać mi swój numer IBAN", WHY),
]


def main() -> None:
    apply_mode = "--apply" in sys.argv
    engine = create_engine(settings.DATABASE_URL_SYNC)
    ok: list[tuple[int, str, str, str, str]] = []
    skipped: list[tuple[int, str, str | None]] = []
    seen: set[tuple[int, str]] = set()
    dupes: list[tuple[int, str]] = []
    with engine.connect() as conn:
        for wid, col, was, now, why in FIXES:
            if (wid, col) in seen:
                dupes.append((wid, col))
            seen.add((wid, col))
            cur = conn.execute(
                text(f"SELECT {col} FROM words WHERE id = :i"), {"i": wid}
            ).scalar()
            if (cur or "").strip() != was:
                skipped.append((wid, col, cur))
            else:
                ok.append((wid, col, was, now, why))

    print(f"=== правок {len(FIXES)}, совпало {len(ok)}, пропущено {len(skipped)} ===\n")
    for wid, col in dupes:
        print(f"ВНИМАНИЕ: одна ячейка правится дважды — id={wid} {col}")
    for wid, col, cur in skipped:
        print(f"ПРОПУСК id={wid} {col}: в базе {cur!r}")

    if not apply_mode:
        for wid, col, was, now, why in ok:
            print(f"id={wid} {col}")
            print(f"  было:  {was}")
            print(f"  стало: {now}")
        print("\nсухой прогон. применить: --apply")
        return

    with engine.begin() as conn:
        for wid, col, _, now, _ in ok:
            conn.execute(
                text(f"UPDATE words SET {col} = :v WHERE id = :i"),
                {"v": now, "i": wid},
            )
    print(f"\nприменено: {len(ok)}")

    bad = 0
    with engine.connect() as conn:
        for wid, col, _, now, _ in ok:
            cur = conn.execute(
                text(f"SELECT {col} FROM words WHERE id = :i"), {"i": wid}
            ).scalar()
            if (cur or "").strip() != now:
                bad += 1
                print(f"НЕ ЗАПИСАЛОСЬ id={wid} {col}: {cur!r}")
    print(f"самопроверка: не записалось {bad}")


if __name__ == "__main__":
    main()
