"""ТРЕТИЙ ПРОХОД, блок 14 (ряды 2601–2800) — ПОСЛЕДНИЙ: 10 ячеек в 5 рядах.

ТРИ НАХОДКИ, И ВСЕ ТРИ — ПРОДОЛЖЕНИЕ КЛАССОВ, ОТКРЫТЫХ В ЭТОМ ЖЕ ПРОХОДЕ.

════════════════════════════════════════════════════════════════════════
1. ЖЕНСКИЙ РЯД НЕСЁТ СОДЕРЖИМОЕ МУЖСКОГО — ПРИ ТОМ, ЧТО МУЖСКОЙ РЯД ЕСТЬ
════════════════════════════════════════════════════════════════════════

`die Verlobte` (15008, B1):

    ru  невеста, ЖЕНИХ          en  fiancée, FIANCÉ
    uk  наречена, НАРЕЧЕНИЙ     pl  narzeczona, NARZECZONY

А рядом в базе стоит `der Verlobte` (15043, B2) ровно с этим: «жених,
обручённый». То есть женский ряд пересказывает мужской, и ученик, открыв
карточку «die Verlobte», может получить «жениха».

Это тот же разряд, что класс рода из блока 10 («das Schild» со щитом), но
устроен иначе: здесь написание у пары ОДИНАКОВОЕ («der/die Verlobte»), и
значение несёт только артикль. Проверка поэтому другая: **есть ли в базе
отдельный ряд другого рода.** Если есть — чужое значение в списке лишнее,
потому что ему есть где жить.

ЗАМЕР по женским субстантивированным рядам: пары «-ая / -ый» в русском
списке — **2 попадания**, оба дефектные:

    die Verlobte   (15008)  «невеста, жених»  — мужской ряд 15043 есть
    die Geschworene(16509)  «присяжная, присяжный» — мужской 16890 есть

И третье попадание нашлось чтением рядом: `die Abgeordnete` (16466) pl
«posłanka, deputowana, POSEŁ» — «poseł» мужская форма, а мужской ряд
16322 `der Abgeordnete` с «poseł, deputowany» стоит рядом.

ПОЧЕМУ `die Bekannte` (2263) «знакомая, знакомый» ОСТАВЛЕНА. Мужского
ряда `der Bekannte` в базе НЕТ. Убрать «знакомый» значило бы потерять
мужское значение совсем — а это уже не правка текста, а решение о составе
базы. Вынесено владельцу.

ПОЧЕМУ `die Abgeordnete` ru «депутат, депутатка, парламентарий» ТРОНУТА
ТОЛЬКО В ПОЛЬСКОМ. По-русски «депутат» — не мужская форма, а общая:
женщину тоже называют депутатом, и феминитив «депутатка» стоит рядом как
уточнение. По-польски «poseł» и «posłanka» разведены жёстко, и «poseł» —
именно мужская. Правится там, где язык различает, и не правится там, где
не различает. Ср. `die Ärztin` (12533) ru «врач, женщина-врач, доктор»:
«врач» тут тоже общая форма, и ряд верен.

════════════════════════════════════════════════════════════════════════
2. ДВА СУЩЕСТВИТЕЛЬНЫХ ПОДРЯД БЕЗ СВЯЗИ — ПОСЛЕДНИЙ СЛУЧАЙ КЛАССА
════════════════════════════════════════════════════════════════════════

`die Cola` (154, A1) ru «кола, ГАЗИРОВКА КОЛА». Ровно та же болезнь, что
`Krone` (9746) «крона деньги» и `Stiefel` (1914) «ботинок высокий» из
блока 11: слово и пояснение склеены без связи и по-русски не читаются.
Здесь достаточно убрать второе слово: «кола, газировка» — связная пара
синонимов, и украинский с польским давно стоят одним словом.

════════════════════════════════════════════════════════════════════════
3. ТИРЕ ДИАЛОГА ПОТЕРЯНО В ОДНОМ ЯЗЫКЕ
════════════════════════════════════════════════════════════════════════

Блок 13 привёл знак тире к единообразию по языкам. Здесь проверено
другое: **не потерян ли знак там, где он нужен по смыслу.** Замер по 25
рядам с тире в немецком примере: в трёх знак отсутствует хоть в одном
языке, и дефект один:

    nö (13957)  de «Kommst du mit ins Kino? – Nö, hab keine Lust»
                pl «Idziesz do kina? Nie, nie mam ochoty»

Это ДИАЛОГ: вопрос и ответ разных людей. Все остальные языки границу
отмечают, польский — нет, и фраза читается как речь одного человека. У
ряда-близнеца `nee` (13877) польский стоит правильно: «Idziesz z nami? –
Nie, nie mam ochoty» — то есть приём базы есть, и он просто не применён.

Два законных случая из трёх: `Rattenloch` (8687) en «like a rat hole,
dark and dirty» — запятая по-английски здесь нормальна, а турецкий
перестроил фразу вовсе; `Rasenmäher` (18372) pl «Kosiarka się zepsuła,
trzeba kupić nową» — по-польски запятая законна.

════════════════════════════════════════════════════════════════════════
ЧТО ПРОВЕРЕНО В БЛОКЕ И ОСТАВЛЕНО
════════════════════════════════════════════════════════════════════════

    Nacken (12554)  ru «шея, затылок, задняя часть шеи» — «шея» первым,
        хотя `Nacken` это затылок. Но пример выбирает «затылок», и
        по-русски «болит шея» о затылке говорят. Не дефект.
    Anwältin (8823)  ru «Мой адвокат СКАЗАЛА» — женский глагол при
        мужском существительном. Это норма русского согласования по полу
        носителя, разобранная на `Hoheit` (15961) в блоке 7.
    Unschuldige (16052), bedaure (10350)  заголовки не в словарной форме;
        это открытый класс в куче владельца.
    vorüber (18685)  pl «minąć, skończony, minięty, obok» — инфинитив в
        наречном ряду выглядит странно, но польский так и говорит
        («wszystko minęło»), а трогать морфологию чужого языка без
        прямого основания — лишний риск.
"""

from __future__ import annotations

import sys

from sqlalchemy import create_engine, text

from app.config import settings

W_GENDER = "мужская форма живёт в своём ряду; здесь артикль «die»"
W_JOIN = "два существительных подряд без связи, как «крона деньги»"
W_DASH = "диалог: граница реплик отмечена во всех языках, кроме польского"

FIXES: list[tuple[int, str, str, str, str]] = [
    # --- die Verlobte (15008): мужское живёт в ряду 15043
    (15008, "translation_en", "fiancée, fiancé", "fiancée", W_GENDER),
    (15008, "translation_ru", "невеста, жених", "невеста", W_GENDER),
    (15008, "translation_uk", "наречена, наречений", "наречена", W_GENDER),
    (15008, "translation_pl", "narzeczona, narzeczony", "narzeczona", W_GENDER),
    # --- die Geschworene (16509): мужское живёт в ряду 16890
    (16509, "translation_ru", "присяжная, присяжный, член суда присяжных",
     "присяжная, член суда присяжных", W_GENDER),
    (16509, "translation_uk", "присяжна, присяжний, член суду присяжних",
     "присяжна, член суду присяжних", W_GENDER),
    (16509, "translation_pl", "przysięgła, przysięgły, członek ławy przysięgłych",
     "przysięgła, członek ławy przysięgłych", W_GENDER),
    # --- die Abgeordnete (16466): по-польски «poseł» мужская форма, ряд 16322
    (16466, "translation_pl", "posłanka, deputowana, poseł",
     "posłanka, deputowana", W_GENDER),
    # --- die Cola (154)
    (154, "translation_ru", "кола, газировка кола", "кола, газировка", W_JOIN),
    # --- nö (13957): тире диалога
    (13957, "example_pl", "Idziesz do kina? Nie, nie mam ochoty",
     "Idziesz do kina? – Nie, nie mam ochoty", W_DASH),
]


def main() -> None:
    apply_mode = "--apply" in sys.argv
    engine = create_engine(settings.DATABASE_URL_SYNC)
    ok: list[tuple[int, str, str, str, str]] = []
    skipped: list[tuple[int, str, str | None]] = []
    seen: set[tuple[int, str]] = set()
    dupes: list[tuple[int, str]] = []
    with engine.connect() as conn:
        for wid, col, was, now, why in FIXES:
            if (wid, col) in seen:
                dupes.append((wid, col))
            seen.add((wid, col))
            cur = conn.execute(
                text(f"SELECT {col} FROM words WHERE id = :i"), {"i": wid}
            ).scalar()
            if (cur or "").strip() != was:
                skipped.append((wid, col, cur))
            else:
                ok.append((wid, col, was, now, why))

    print(f"=== правок {len(FIXES)}, совпало {len(ok)}, пропущено {len(skipped)} ===\n")
    for wid, col in dupes:
        print(f"ВНИМАНИЕ: одна ячейка правится дважды — id={wid} {col}")
    for wid, col, cur in skipped:
        print(f"ПРОПУСК id={wid} {col}: в базе {cur!r}")

    if not apply_mode:
        for wid, col, was, now, why in ok:
            print(f"id={wid} {col}")
            print(f"  было:  {was}")
            print(f"  стало: {now}")
        print("\nсухой прогон. применить: --apply")
        return

    with engine.begin() as conn:
        for wid, col, _, now, _ in ok:
            conn.execute(
                text(f"UPDATE words SET {col} = :v WHERE id = :i"),
                {"v": now, "i": wid},
            )
    print(f"\nприменено: {len(ok)}")

    bad = 0
    with engine.connect() as conn:
        for wid, col, _, now, _ in ok:
            cur = conn.execute(
                text(f"SELECT {col} FROM words WHERE id = :i"), {"i": wid}
            ).scalar()
            if (cur or "").strip() != now:
                bad += 1
                print(f"НЕ ЗАПИСАЛОСЬ id={wid} {col}: {cur!r}")
    print(f"самопроверка: не записалось {bad}")


if __name__ == "__main__":
    main()
